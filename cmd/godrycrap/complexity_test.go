func TestComplexityReportsBeforeAndAfter(t *testing.T) {
	r := newRepo(t)
	r.stage(map[string]string{"p/a.go": "package p\n" + fn("Grow", 3) + fn("Same", 2)})
	r.commit("base")
	r.stage(map[string]string{"p/a.go": "package p\n" + fn("Grow", 5) + fn("Same", 2) + fn("Added", 1)})
	res := r.run("complexity", "-format", "json")
	res.want(t, gate.OK)
	var payload struct {
		Functions []complexityRow `json:"functions"`
	}
	if err := json.Unmarshal([]byte(res.stdout), &payload); err != nil {
		t.Fatal(err)
	}
	got := map[string]complexityRow{}
	for _, row := range payload.Functions {
		got[row.Name] = row
	}
	if len(got) != 2 {
		t.Fatalf("rows = %+v, want Grow and Added only", payload.Functions)
	}
	if g := got["Grow"]; g.Before == nil || *g.Before != 3 || g.CC != 5 {
		t.Errorf("Grow = %+v, want 3 -> 5", g)
	}
	if a := got["Added"]; a.Before != nil || a.CC != 1 {
		t.Errorf("Added = %+v, want new with CC 1", a)
	}
}

