func TestComplexityDiffRange(t *testing.T) {
	r := newRepo(t)
	r.stage(map[string]string{"p/a.go": "package p\n" + fn("F", 2)})
	base := r.commit("base")
	r.stage(map[string]string{"p/a.go": "package p\n" + fn("F", 10)})
	r.commit("head")
	r.stage(map[string]string{"p/a.go": "package p\n" + fn("F", 1)})
	r.run("complexity", "-diff", base+"..HEAD", "-format", "tsv").want(t, gate.Fail, "fail\t10\t2\texample.com/m/p.F")
	r.run("complexity", "-diff", "main...HEAD").want(t, gate.OK, "0 functions")
	r.run("complexity", "-diff", "nope..HEAD").want(t, gate.Error, "unknown revision")
	r.run("complexity", "-diff", "HEAD").want(t, gate.Error, "want BASE..HEAD")
}

func TestComplexityRatchet(t *testing.T) {
	r := newRepo(t)
	r.stage(map[string]string{"p/a.go": "package p\n" + fn("Legacy", 12) + fn("Worse", 12)})
	r.commit("base")
	r.stage(map[string]string{"p/a.go": "package p\n" + fn("Legacy", 11) + fn("Worse", 13) + fn("Fresh", 10)})
	r.run("complexity").want(t, gate.Fail)
	res := r.run("complexity", "-ratchet", "-format", "tsv")
	res.want(t, gate.Fail, "warn\t11\t12\texample.com/m/p.Legacy", "fail\t13\t12\texample.com/m/p.Worse", "fail\t10\tnew\texample.com/m/p.Fresh")
	r.stage(map[string]string{"p/a.go": "package p\n" + fn("Legacy", 11) + fn("Worse", 12)})
	r.run("complexity", "-ratchet").want(t, gate.Warn)
}

