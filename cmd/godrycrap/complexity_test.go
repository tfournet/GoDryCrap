func TestComplexityThresholdFixtures(t *testing.T) {
	cases := []struct {
		name   string
		status gate.Status
	}{
		{"CC9", gate.Warn},
		{"CC10", gate.Fail},
		{"CC11", gate.Fail},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			r := newRepo(t)
			file := strings.ToLower(tc.name) + ".go"
			r.fixture("p/"+file, "complexity/"+file)
			r.git("add", "p/"+file)
			r.run("complexity").want(t, tc.status, "example.com/m/p."+tc.name, "p/"+file+":")
		})
	}
}

