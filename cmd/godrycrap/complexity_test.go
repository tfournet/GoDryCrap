func TestComplexityMarkdownAndSummary(t *testing.T) {
	r := newRepo(t)
	r.stage(map[string]string{"p/a.go": "package p\n" + fn("F", 9)})
	summary := filepath.Join(t.TempDir(), "summary.md")
	t.Setenv("GITHUB_STEP_SUMMARY", summary)
	res := r.run("complexity", "-format", "markdown", "-summary")
	want := "### godrycrap complexity\n\n1 functions, 0 fail, 1 warn\n\n| status | cc | before | function | location |\n| --- | --- | --- | --- | --- |\n| warn | 9 | new | example.com/m/p.F | p/a.go:2 |\n"
	res.want(t, gate.Warn, want)
	data, err := os.ReadFile(summary)
	if err != nil || !strings.Contains(string(data), want) {
		t.Errorf("summary = %q, %v", data, err)
	}
}

