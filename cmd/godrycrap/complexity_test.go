// initFn is an init function of complexity n; tag makes its text distinct.
func initFn(n, tag int) string {
	src := fmt.Sprintf("func init() {\n\tx := %d\n", tag)
	for i := 1; i < n; i++ {
		src += "\tif x > 0 {\n\t\tx--\n\t}\n"
	}
	return src + "\t_ = x\n}\n"
}

// TestComplexityRepeatedInits is round 2's finding 2: deleting or adding an
// init must not turn an unchanged high-CC init into a new failing one.
func TestComplexityRepeatedInits(t *testing.T) {
	survivor := initFn(12, 1)
	r := newRepo(t)
	r.stage(map[string]string{"p/a.go": "package p\n" + survivor + initFn(2, 2)})
	r.commit("base")

	r.stage(map[string]string{"p/a.go": "package p\n" + survivor})
	for _, args := range [][]string{{"complexity"}, {"complexity", "-ratchet"}} {
		r.run(args...).want(t, gate.OK, "0 functions")
	}
	r.commit("delete the second init")

	r.stage(map[string]string{"p/a.go": "package p\n" + initFn(3, 3) + survivor})
	for _, args := range [][]string{{"complexity", "-format", "tsv"}, {"complexity", "-ratchet", "-format", "tsv"}} {
		res := r.run(args...)
		res.want(t, gate.OK, "ok\t3\tnew\texample.com/m/p.init\tp/a.go:2")
		res.lacks(t, "\t12\t")
	}

	r.commit("add an init before it")

	// With the insertion committed, editing the survivor keeps its history.
	r.stage(map[string]string{"p/a.go": "package p\n" + initFn(3, 3) + initFn(13, 1)})
	r.run("complexity", "-ratchet", "-format", "tsv").want(t, gate.Fail, "fail\t13\t12\texample.com/m/p.init")
	r.stage(map[string]string{"p/a.go": "package p\n" + initFn(3, 3) + initFn(11, 1)})
	r.run("complexity", "-ratchet", "-format", "tsv").want(t, gate.Warn, "warn\t11\t12\texample.com/m/p.init")
}

// TestComplexityRelocatedNestedModule is round 3's finding 2: a nested
// module moved to another directory, its go.mod still declaring the same
// path, keeps its functions' identity on both sides of the diff.
func TestComplexityRelocatedNestedModule(t *testing.T) {
	r := newRepo(t)
	r.stage(map[string]string{
		"old/go.mod": "module example.com/nested\n",
		"old/p/a.go": "package p\n" + fn("F", 10),
	})
	base := r.commit("nested module under old/")
	r.git("mv", "old", "new")

	want := "warn\t10\t10\texample.com/nested/p.F\tnew/p/a.go:2"
	r.run("complexity", "-format", "tsv").want(t, gate.Fail, "fail\t10\t10\texample.com/nested/p.F\tnew/p/a.go:2")
	r.run("complexity", "-ratchet", "-format", "tsv").want(t, gate.Warn, want)

	r.commit("move it to new/")
	r.run("complexity", "-ratchet", "-format", "tsv", "-diff", base+"..HEAD").want(t, gate.Warn, want)
	r.run("complexity", "-ratchet", "-format", "tsv", "-diff", base+"...HEAD").want(t, gate.Warn, want)
}
