func TestComplexityPathModeSkipsGeneratedDirsWhenNamed(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "go.mod"), "module example.com/m\n")
	for _, p := range []string{"gen/a.go", "ent/b.go", "ent/subpkg/c.go", "pkg/gen/d.go"} {
		writeFile(t, filepath.Join(dir, p), "package x\n"+fn("Machine", 12))
	}
	writeFile(t, filepath.Join(dir, "pkg/kept.go"), "package pkg\n"+fn("Kept", 2))
	writeFile(t, filepath.Join(dir, "pkg/testdata/fixture.go"), "package fixture\n"+fn("Fixture", 2))
	targets := []string{
		dir,
		filepath.Join(dir, "gen"),
		filepath.Join(dir, "ent", "subpkg"),
		filepath.Join(dir, "gen", "a.go"),
		filepath.Join(dir, "ent", "b.go"),
		filepath.Join(dir, "pkg", "gen", "d.go"),
	}
	for _, target := range targets {
		res := runIn(t, "complexity", "-format", "tsv", target)
		res.want(t, gate.OK)
		res.lacks(t, ".Machine")
	}
	runIn(t, "complexity", "-format", "tsv", dir).want(t, gate.OK, "example.com/m/pkg.Kept")
	runIn(t, "complexity", "-format", "tsv", filepath.Join(dir, "pkg", "testdata")).want(t, gate.OK, "Fixture")
	runIn(t, "crap", "-coverprofile", writeProfile(t), filepath.Join(dir, "gen", "a.go")).want(t, gate.OK, "0 functions")
}

